import type { OperationsManifestConfig } from './config';

export interface Entry {
	tool: string;
	description: string;
	document: string;
	variables: string | undefined;
}

function quote(text: string): string {
	return `'${text
		.replace(/\\/g, '\\\\')
		.replace(/'/g, "\\'")
		.replace(/\n/g, '\\n')
		.replace(/\r/g, '\\r')
		.replace(/\u2028/g, '\\u2028')
		.replace(/\u2029/g, '\\u2029')}'`;
}

function importLine(names: string[], from: string): string[] {
	const one = `import { ${names.join(', ')} } from ${quote(from)};`;
	if (one.length <= 80) return [one];
	return ['import {', ...names.map((n) => `\t${n},`), `} from ${quote(from)};`];
}

// Biome moves a value that overflows 80 columns to its own line.
function property(key: string, value: string): string[] {
	const line = `\t\t${key}: ${value},`;
	return line.replaceAll('\t', '  ').length <= 80
		? [line]
		: [`\t\t${key}:`, `\t\t\t${value},`];
}

/** The manifest source: sorted entries, tabs and single quotes. */
export function render(
	entries: Entry[],
	config: OperationsManifestConfig,
): string {
	const sorted = [...entries].sort((a, b) =>
		a.tool < b.tool ? -1 : a.tool > b.tool ? 1 : 0,
	);
	const schemas = [
		...new Set(sorted.flatMap((e) => (e.variables ? [e.variables] : []))),
	].sort();
	const lines = [
		'// Generated by @nxgt/ai-graphql/codegen. Do not edit.',
		`import type { GraphqlOperation } from ${quote(config.typesImport ?? '@nxgt/ai-graphql')};`,
	];
	if (schemas.length > 0) {
		lines.push(...importLine(schemas, config.zodImport ?? './zod'));
	}
	lines.push('', `export const ${config.exportName ?? 'operations'} = [`);
	for (const e of sorted) {
		lines.push(
			'\t{',
			...property('name', quote(e.tool)),
			...property('description', quote(e.description)),
			...property('document', quote(e.document)),
		);
		if (e.variables) lines.push(...property('variables', e.variables));
		lines.push('\t},');
	}
	lines.push('] satisfies readonly GraphqlOperation[];', '');
	return lines.join('\n');
}
